def icon_names() -> list[str]:
    """返回内置的全部 18 个图标名。"""
    return sorted(_SVG_B64)


def svg_sources() -> dict[str, str]:
    """返回全部 SVG 模板源码（currentColor 占位为 __COLOR__）。"""
    return {
        name: base64.b64decode(b64).decode("utf-8")
        for name, b64 in _SVG_B64.items()
    }


def get_svg(name: str, color: str = "#000000") -> str | None:
    """取一个图标的 SVG 源码，把 ``currentColor`` / ``__COLOR__`` 替换成 ``color``。"""
    b64 = _SVG_B64.get(name)
    if not b64:
        return None
    svg = base64.b64decode(b64).decode("utf-8")
    svg = svg.replace("__COLOR__", color).replace("currentColor", color)
    return svg


def svg_data_uri(name: str, color: str = "#000000") -> str:
    """返回可直接用于 ``<img src>`` / CSS ``background-image`` 的 data URI。

    未知图标返回空字符串，模板里用 ``{% if %}`` 判断即可降级。
    """
    svg = get_svg(name, color)
    if not svg:
        return ""
    svg = re.sub(r">\s+<", "><", svg).strip()
    return "data:image/svg+xml," + quote(svg, safe="")


def platform_icon(slug: str, color: str | None = None) -> str:
    """按平台 slug 返回带品牌色的 data URI；未知平台返回空字符串。"""
    name = PLATFORM_ICONS.get(slug)
    if not name:
        return ""
    return svg_data_uri(name, color or PLATFORM_COLORS.get(slug, "#334155"))


def platform_icon_map(color_by_slug: dict[str, str] | None = None) -> dict[str, str]:
    """批量生成 ``{slug: data_uri}``；``color_by_slug`` 可覆盖单个平台颜色。"""
    overrides = color_by_slug or {}
    return {
        slug: platform_icon(slug, overrides.get(slug))
        for slug in PLATFORM_ICONS
    }


