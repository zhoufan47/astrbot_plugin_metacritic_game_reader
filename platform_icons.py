# 官方同款：Iconify / UnoCSS 风格的 CSS mask 规则
# --------------------------------------------------------------------------- #
def mask_data_uri(name: str) -> str:
    """生成用于 CSS ``mask-image`` 的**黑色剪影** SVG data URI。

    与 Metacritic 页面内联 CSS 完全一致：SVG 里 ``fill='black'``，但颜色不由
    SVG 决定 —— mask 只取 alpha 轮廓，实际颜色来自元素的
    ``background-color:currentColor``。
    """
    svg = get_svg(name, "black")
    if not svg:
        return ""
    svg = re.sub(r">\s+<", "><", svg).strip()
    # 单引号更贴近站点原始输出，同时避免 CSS 字符串里出现双引号
    svg = svg.replace('"', "'")
    return "data:image/svg+xml," + quote(svg, safe="")


def iconify_css(names: list[str] | None = None) -> str:
    """生成与 Metacritic 官方 UnoCSS preset-icons 一致的 CSS 规则。

    产出的规则形如（已实测与页面 CSS 等价）::

        .iconify{display:inline-block;...}
        :where(.i-mc-platform\\:pclogo){
          display:inline-block;width:1.73em;height:1em;
          background-color:currentColor;
          -webkit-mask-image:var(--svg);mask-image:var(--svg);
          ...
          --svg:url("data:image/svg+xml,%3Csvg ... /%3E")
        }

    用法：把返回的文本放进模板 ``<style>`` 里（模板中 ``{{ iconify_css }}``，
    需标 ``|safe``），然后写
    ``<span class="iconify i-mc-platform:pclogo"></span>``，
    通过给父元素设 ``color`` 即可改变 logo 颜色。

    Args:
        names: 需要的图标名列表；None 表示全部 18 个。
    """
    targets = sorted(set(names or _SVG_B64.keys()))
    base = """
.iconify{display:inline-block;flex:0 0 auto;vertical-align:middle;
  background-color:currentColor;
  -webkit-mask-repeat:no-repeat;mask-repeat:no-repeat;
  -webkit-mask-size:100% 100%;mask-size:100% 100%;
  -webkit-mask-position:center;mask-position:center}
"""
    rules = [base.strip()]
    for name in targets:
        b64 = _SVG_B64.get(name)
        if not b64:
            continue
        # 每个图标的原始宽高（从 SVG 模板里解析）
        svg = base64.b64decode(b64).decode("utf-8")
        wm = re.search(r'width="(\d+)"', svg)
        hm = re.search(r'height="(\d+)"', svg)
        w = int(wm.group(1)) if wm else 24
        h = int(hm.group(1)) if hm else 24
        ratio = round(w / h, 4) if h else 1.73
        uri = mask_data_uri(name)
        if not uri:
            continue
        # CSS 选择器里的冒号需转义；--svg 变量用双引号包裹 data URI
        safe_name = re.sub(r"[^A-Za-z0-9_-]", "", name)
        rules.append(
            ":where(.i-mc-platform\\:"
            + safe_name
            + "){display:inline-block;width:"
            + str(ratio)
            + "em;height:1em;"
            + "-webkit-mask-image:var(--svg);mask-image:var(--svg);"
            + '--svg:url("'
            + uri
            + '")}'
        )
    return "\n".join(rules)


def platform_iconify_class(slug: str) -> str:
    """返回平台对应的官方 iconify class（如 ``i-mc-platform:pclogo-bold``）。

    未知平台返回空字符串，模板里用 ``{% if %}`` 判断即可降级。
    """
    name = PLATFORM_ICONS.get(slug)
    return f"i-mc-platform:{name}" if name else ""
